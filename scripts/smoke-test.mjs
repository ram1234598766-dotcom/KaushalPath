import { readFileSync, existsSync } from "node:fs";
import assert from "node:assert/strict";
const html = readFileSync(new URL("../public/index.html", import.meta.url), "utf8");
const app = readFileSync(new URL("../public/app.js", import.meta.url), "utf8");
const fn = readFileSync(new URL("../netlify/functions/study-guide.mjs", import.meta.url), "utf8");
const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const toml = readFileSync(new URL("../netlify.toml", import.meta.url), "utf8");
assert.match(html, /KaushalPath/, "site brand should be present");
assert.match(html, /studyForm/, "study form should exist");
assert.match(html, /sourceUrls/, "manual website URL input should exist");
assert.match(html, /liveSearch/, "live search toggle should exist");
assert.match(html, /src="\/app\.js" defer/, "JavaScript should be external for CSP");
assert.doesNotMatch(html, /<script>[\s\S]*?<\/script>/i, "inline scripts should be removed");
assert.match(app, /\/api\/study-guide/, "frontend must call the Netlify function");
assert.match(app, /urls:urls/, "frontend must send supplied URLs");
assert.match(fn, /client\.interactions\.create/, "AI uses Interactions API");
assert.match(fn, /google_search/, "AI supports live search");
assert.match(fn, /url_context/, "AI supports website reading");
assert.match(fn, /normalizeUrls/, "user URLs are validated");
assert.equal(pkg.dependencies["@google/genai"], "^2.30.0", "SDK version should support URL context");
assert.match(toml, /Content-Security-Policy/);
assert.match(toml, /script-src 'self'/, "CSP should block injected inline Netlify badge script");
assert.ok(existsSync(new URL("../netlify/functions/study-guide.mjs", import.meta.url)), "AI function exists");
console.log("KaushalPath AI, URL reading, CSP and smoke tests passed.");
